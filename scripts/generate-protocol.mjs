import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const manifest = JSON.parse(readFileSync(join(root, 'engine-manifest.json'), 'utf8'))
const localCli = resolve(root, '..', '..', 'Rinari-CLI')
const localSchema = join(localCli, 'src', 'rinari', 'engine_protocol', 'schema', 'v1.json')
let localIsPinned = false
if (existsSync(localSchema)) {
  try {
    localIsPinned = execFileSync('git', ['-C', localCli, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim()
      === manifest.engine_git_sha
  } catch {
    localIsPinned = false
  }
}
// The schema digest is part of the generated output and `--check` compares
// text byte-for-byte. A Windows checkout with core.autocrlf turns the LF blob
// into CRLF, so both the source and the existing outputs are normalized to LF
// before hashing/comparing; otherwise CI on Linux reports the files as stale.
const normalizeEol = (text) => text.replace(/\r\n/g, '\n')

const schemaSource = process.env.RINARI_ENGINE_SCHEMA
const rawSchemaText = schemaSource
  ? readFileSync(resolve(schemaSource), 'utf8')
  : localIsPinned
    ? readFileSync(localSchema, 'utf8')
    : await fetch(
        `https://raw.githubusercontent.com/${manifest.engine_repository}/${manifest.engine_git_sha}/src/rinari/engine_protocol/schema/v1.json`,
      ).then((response) => {
        if (!response.ok) throw new Error(`Could not fetch pinned protocol schema (${response.status}).`)
        return response.text()
      })
const schemaText = normalizeEol(rawSchemaText)

const schema = JSON.parse(schemaText)
const digest = createHash('sha256').update(schemaText).digest('hex')
const methods = schema.$defs.method.enum
const events = schema.$defs.event.enum
const definitionNames = schema['x-codegen-definitions'] ?? []

const pascal = (value) => value
  .split(/[^A-Za-z0-9]+/)
  .filter(Boolean)
  .map((part) => part[0].toUpperCase() + part.slice(1))
  .join('')

// `anyOf: [{ $ref }, { type: 'null' }]` is how the schema spells a nullable
// object reference (JSON Schema has no `type: [ref, null]`).
function nullableRef(node) {
  if (!Array.isArray(node.anyOf) || node.anyOf.length !== 2) return null
  const reference = node.anyOf.find((branch) => branch.$ref)
  const nothing = node.anyOf.find((branch) => branch.type === 'null')
  return reference && nothing ? reference : null
}

function tsType(node) {
  const optionalRef = nullableRef(node)
  if (optionalRef) return `${tsType(optionalRef)} | null`
  if (node.$ref) return pascal(node.$ref.split('/').at(-1))
  if ('const' in node) return JSON.stringify(node.const)
  if (node.enum) return node.enum.map((item) => JSON.stringify(item)).join(' | ')
  if (Array.isArray(node.type)) {
    return node.type.map((type) => type === 'null' ? 'null' : tsType({ ...node, type })).join(' | ')
  }
  if (node.type === 'string') return 'string'
  if (node.type === 'integer' || node.type === 'number') return 'number'
  if (node.type === 'boolean') return 'boolean'
  if (node.type === 'array') return `Array<${tsType(node.items ?? {})}>`
  if (node.type === 'object') return `Record<string, ${typeof node.additionalProperties === 'object' ? tsType(node.additionalProperties) : 'unknown'}>`
  return 'unknown'
}

const tsDefinitions = definitionNames.map((name) => {
  const definition = schema.$defs[name]
  const required = new Set(definition.required ?? [])
  const fields = Object.entries(definition.properties ?? {}).map(([field, node]) =>
    `  ${field}${required.has(field) ? '' : '?'}: ${tsType(node)}`
  )
  return `export interface ${pascal(name)} {\n${fields.join('\n')}\n}`
}).join('\n\n')

const ts = `// @generated by scripts/generate-protocol.mjs — DO NOT EDIT.\n// Source: Rinari Engine Protocol v1 (sha256:${digest})\n\nexport const ENGINE_METHODS = ${JSON.stringify(methods, null, 2)} as const\nexport type EngineMethod = (typeof ENGINE_METHODS)[number]\n\nexport const ENGINE_EVENTS = ${JSON.stringify(events, null, 2)} as const\nexport type EngineEventName = (typeof ENGINE_EVENTS)[number]\n\n${tsDefinitions}\n`

const outputs = [
  [join(root, 'src', 'types', 'protocol.generated.ts'), ts],
]
const check = process.argv.includes('--check')
for (const [path, content] of outputs) {
  if (check) {
    if (!existsSync(path) || normalizeEol(readFileSync(path, 'utf8')) !== content) {
      throw new Error(`${path} is stale. Run npm run protocol:generate.`)
    }
  } else {
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, content)
  }
}
console.log(check ? 'Generated protocol files are current.' : 'Generated protocol files updated.')
